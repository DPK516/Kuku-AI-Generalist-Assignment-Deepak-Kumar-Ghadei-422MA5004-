// Unit tests for the deterministic safety layer of the AI lawyer (no API calls).
import { guardCitations, redFlags } from '../public/js/lawyer/agent.js';
let fail = 0;
const t = (name, cond) => { console.log(`${cond ? 'PASS' : 'FAIL'}  ${name}`); if (!cond) fail++; };
const keep = (s) => guardCitations(s).removed.length === 0;
const drop = (s) => guardCitations(s).removed.length > 0;
t('keeps verified section+act', keep('Under Section 69 of the Consumer Protection Act, 2019 you have two years.'));
t('keeps NI Act 138', keep('Section 138 of the Negotiable Instruments Act, 1881 applies.'));
t('keeps Hindi dhara 138', keep('चेक बाउंस पर धारा 138 लागू होती है।'));
t('keeps Code on Wages s17', keep('Section 17 of the Code on Wages, 2019 says two working days.'));
t('keeps Order XXXVII', keep('a summary suit under Order XXXVII CPC'));
t('keeps replaced-law mention', keep('The Payment of Wages Act, 1936 was replaced by the Code on Wages, 2019.'));
t('drops IPC 420', drop('This is cheating under Section 420 IPC.'));
t('drops wrong act for real number', drop('Section 12 of the Consumer Protection Act lets you sue.'));
t('drops invented section', drop('Section 21A of the Consumer Protection Act, 2019 gives triple damages.'));
t('drops case law', drop('As held in Ramesh Kumar v. State of Punjab (2015), deposits must be returned.'));
t('drops SCC citation', drop('See (2019) 4 SCC 123.'));
t('drops Article 21', drop('Your right to shelter under Article 21 is violated.'));
t('drops unknown statute', drop('The Delhi Rent Control Act, 1958 caps deposits.'));
t('drops hindi invented dhara', drop('धारा 406 के तहत केस करें।'));
const r = guardCitations('Under Section 420 IPC and Section 69 of the Consumer Protection Act, 2019.');
t('partial redaction keeps the good one', r.text.includes('Section 69') && !r.text.includes('420'));
t('red flag: police', redFlags('the police came and filed an FIR against me').level === 'lawyer');
t('red flag: urgent', redFlags('my husband beat me last night').level === 'urgent');
t('red flag: big amount', redFlags('they owe me 25 lakh rupees').level === 'lawyer');
t('red flag: rupees', redFlags('deposit of ₹15,00,000 not returned').level === 'lawyer');
t('no flag: "will" as a verb (v5 regression)', redFlags('He says he will deduct painting charges but will not show any bill').level === null);
t('flag: a last will', redFlags('my father left a last will and my brother is fighting it').level === 'lawyer');
t('no flag: deposit', redFlags('my landlord is not returning my 30000 deposit').level === null);
console.log(fail ? `\n${fail} FAILED` : '\nall passed');
process.exit(fail ? 1 : 0);
